"""Generate frontend request/status types from the actual FastAPI OpenAPI schema."""
import json
import os
import sys
import tempfile
from pathlib import Path

backend = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(backend))


def ts(schema):
    if "$ref" in schema:
        return "ApiSchemas[" + json.dumps(schema["$ref"].split("/")[-1]) + "]"
    if "anyOf" in schema:
        return " | ".join(ts(s) for s in schema["anyOf"])
    if "enum" in schema:
        return " | ".join(json.dumps(v) for v in schema["enum"])
    if schema.get("type") == "array":
        return "Array<" + ts(schema.get("items", {})) + ">"
    if schema.get("type") == "object":
        required = schema.get("required", [])
        fields = [json.dumps(k) + ("" if k in required else "?") + ": " + ts(v) + ";" for k,v in schema.get("properties", {}).items()]
        if not fields:
            return "Record<string, " + (ts(schema["additionalProperties"]) if isinstance(schema.get("additionalProperties"), dict) else "unknown") + ">"
        return "{ " + " ".join(fields) + " }"
    return {"string": "string", "number": "number", "integer": "number", "boolean": "boolean", "null": "null"}.get(schema.get("type"), "unknown")


with tempfile.TemporaryDirectory(prefix="momo-openapi-") as scratch:
    os.environ["QUANT_RUNTIME_DIR"] = scratch
    os.environ["QUANT_DB_PATH"] = str(Path(scratch) / "fixture.db")
    os.environ["QUANT_BACKEND_LOG"] = str(Path(scratch) / "log")
    import main
    schemas = main.app.openapi()["components"]["schemas"]
    content = "// Generated by backend/scripts/generate_api_types.py. Do not edit.\nexport interface ApiSchemas {\n" + "\n".join("  " + json.dumps(name) + ": " + ts(schema) + ";" for name,schema in sorted(schemas.items())) + "\n}\n"
    output = backend.parent / "frontend/src/api/schema.generated.ts"
    if "--check" in sys.argv:
        if not output.exists() or output.read_text() != content:
            raise SystemExit("OpenAPI types have drifted; run npm run api:types")
    else:
        output.write_text(content)
    print("OpenAPI types verified" if "--check" in sys.argv else "OpenAPI types generated")
